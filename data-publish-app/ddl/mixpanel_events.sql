-- ============================================================================
-- USER PROFILES TABLE (Mirrors Mixpanel User Profile Structure)
-- ============================================================================
CREATE TABLE mixpanel_user_profiles (
    -- ========================================================================
    -- INTERNAL IDENTIFIER
    -- ========================================================================
    id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    
    -- ========================================================================
    -- CORE IDENTITY
    -- ========================================================================
    distinct_id                 VARCHAR(255) NOT NULL COMMENT 'Unique user identifier',
    
    -- ========================================================================
    -- GEOLOCATION PROPERTIES (Auto-collected)
    -- ========================================================================
    `$city`                     VARCHAR(255) COMMENT 'City of user',
    `$region`                   VARCHAR(255) COMMENT 'Region/State of user',
    `$country_code`             CHAR(2) COMMENT 'Country code (ISO 3166-1 alpha-2)',
    `$timezone`                 VARCHAR(100) COMMENT 'User timezone',
    `$geo_source`               VARCHAR(50) COMMENT 'Geolocation source (reverse_geocoding)',
    
    -- ========================================================================
    -- SYSTEM PROPERTIES (Auto-collected by SDKs)
    -- ========================================================================
    `$last_seen`                DATETIME(3) COMMENT 'Last time profile was updated (auto-set)',
    `$created`                  DATETIME(3) COMMENT 'Profile creation timestamp',
    
    -- Library versions
    `$lib_version`              VARCHAR(20) COMMENT 'Last Mixpanel library version',
    `$android_lib_version`      VARCHAR(20) COMMENT 'Last Android library version',
    `$ios_lib_version`          VARCHAR(20) COMMENT 'Last iOS library version',
    `$swift_lib_version`        VARCHAR(20) COMMENT 'Last Swift library version',
    
    -- OS Properties
    `$os`                       VARCHAR(50) COMMENT 'Last OS',
    `$android_os`               VARCHAR(50) COMMENT 'Android OS (when used)',
    `$android_os_version`       VARCHAR(50) COMMENT 'Last Android OS version',
    `$ios_version`              VARCHAR(50) COMMENT 'Last iOS version',
    
    -- Browser Properties
    `$browser`                  VARCHAR(100) COMMENT 'Last browser',
    `$browser_version`          VARCHAR(50) COMMENT 'Last browser version',
    
    -- App Version Properties
    `$android_app_version`      VARCHAR(50) COMMENT 'Android app version (versionName)',
    `$android_app_version_code` VARCHAR(50) COMMENT 'Android app version code',
    `$ios_app_release`          VARCHAR(50) COMMENT 'iOS app release (CFBundleShortVersionString)',
    `$ios_app_version`          VARCHAR(50) COMMENT 'iOS app version (CFBundleVersion)',
    
    -- Device Properties
    `$android_manufacturer`     VARCHAR(100) COMMENT 'Android device manufacturer',
    `$android_brand`            VARCHAR(100) COMMENT 'Android device brand',
    `$android_model`            VARCHAR(100) COMMENT 'Android device model',
    `$ios_device_model`         VARCHAR(100) COMMENT 'iOS device model',
    
    -- ========================================================================
    -- ATTRIBUTION PROPERTIES (First Touch - JS SDK)
    -- ========================================================================
    `$initial_referrer`         TEXT COMMENT 'Referrer URL on first visit',
    `$initial_referring_domain` VARCHAR(255) COMMENT 'Referring domain on first visit',
    initial_utm_source          VARCHAR(255) COMMENT 'First UTM source',
    initial_utm_medium          VARCHAR(255) COMMENT 'First UTM medium',
    initial_utm_campaign        VARCHAR(255) COMMENT 'First UTM campaign',
    initial_utm_content         VARCHAR(255) COMMENT 'First UTM content',
    initial_utm_term            VARCHAR(255) COMMENT 'First UTM term',
    
    -- ========================================================================
    -- COMMON USER PROPERTIES (Set by application)
    -- ========================================================================
    `$email`                    VARCHAR(320) COMMENT 'User email address',
    `$phone`                    VARCHAR(50) COMMENT 'User phone number',
    `$name`                     VARCHAR(255) COMMENT 'User full name',
    `$first_name`               VARCHAR(100) COMMENT 'User first name',
    `$last_name`                VARCHAR(100) COMMENT 'User last name',
    `$avatar`                   TEXT COMMENT 'User avatar URL',
    
    -- ========================================================================
    -- CUSTOM PROFILE PROPERTIES (Flexible JSON Storage)
    -- ========================================================================
    properties                  JSON COMMENT 'All profile properties as JSON',
    
    -- ========================================================================
    -- METADATA
    -- ========================================================================
    _ingested_at                DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    _updated_at                 DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    
    -- ========================================================================
    -- INDEXES
    -- ========================================================================
    UNIQUE INDEX idx_distinct_id (distinct_id),
    INDEX idx_email (`$email`),
    INDEX idx_phone (`$phone`),
    INDEX idx_name (`$name`(100)),
    INDEX idx_last_seen (`$last_seen`),
    INDEX idx_created (`$created`),
    INDEX idx_country (`$country_code`),
    INDEX idx_city (`$city`(100))
    
) ENGINE=InnoDB 
  DEFAULT CHARSET=utf8mb4 
  COLLATE=utf8mb4_unicode_ci
  ROW_FORMAT=DYNAMIC
  COMMENT='Mixpanel user profiles table';


