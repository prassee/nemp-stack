-- ============================================================================
-- LOOKUP TABLES (Mirrors Mixpanel Lookup Tables Structure)
-- ============================================================================
CREATE TABLE mixpanel_lookup_tables (
    id                          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    
    -- Lookup table metadata
    lookup_table_name           VARCHAR(255) NOT NULL COMMENT 'Name of the lookup table',
    join_key                    VARCHAR(255) NOT NULL COMMENT 'The key used to join with events',
    join_value                  VARCHAR(255) NOT NULL COMMENT 'The value of the join key',
    
    -- Lookup properties as JSON
    properties                  JSON COMMENT 'All lookup table properties',
    
    -- Metadata
    _ingested_at                DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    _updated_at                 DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    
    UNIQUE INDEX idx_lookup (lookup_table_name, join_key, join_value),
