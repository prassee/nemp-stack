    INDEX idx_join_key (join_key)
    
) ENGINE=InnoDB 
  DEFAULT CHARSET=utf8mb4 
  COLLATE=utf8mb4_unicode_ci
  COMMENT='Mixpanel lookup tables for dimension enrichment';


-- ============================================================================
-- VIEWS FOR COMMON MIXPANEL ANALYTICS
-- ============================================================================

-- Daily Active Users (DAU)
CREATE OR REPLACE VIEW v_mixpanel_dau AS
SELECT 
    DATE(time_datetime) AS event_date,
    COUNT(DISTINCT distinct_id) AS daily_active_users,
    COUNT(*) AS total_events
FROM mixpanel_events
GROUP BY DATE(time_datetime)
ORDER BY event_date DESC;


-- Event Counts by Name
CREATE OR REPLACE VIEW v_mixpanel_event_counts AS
SELECT 
    event,
    DATE(time_datetime) AS event_date,
    COUNT(*) AS event_count,
    COUNT(DISTINCT distinct_id) AS unique_users
FROM mixpanel_events
GROUP BY event, DATE(time_datetime)
ORDER BY event_date DESC, event_count DESC;


-- Platform Distribution
CREATE OR REPLACE VIEW v_mixpanel_platform_stats AS
SELECT 
    mp_lib AS platform,
    `$os` AS operating_system,
    DATE(time_datetime) AS event_date,
    COUNT(*) AS event_count,
    COUNT(DISTINCT distinct_id) AS unique_users
FROM mixpanel_events
GROUP BY mp_lib, `$os`, DATE(time_datetime)
ORDER BY event_date DESC, event_count DESC;


-- Geographic Distribution
CREATE OR REPLACE VIEW v_mixpanel_geo_stats AS
SELECT 
    mp_country_code AS country,
    `$region` AS region,
    `$city` AS city,
    DATE(time_datetime) AS event_date,
    COUNT(*) AS event_count,
    COUNT(DISTINCT distinct_id) AS unique_users
FROM mixpanel_events
WHERE mp_country_code IS NOT NULL
GROUP BY mp_country_code, `$region`, `$city`, DATE(time_datetime)
ORDER BY event_date DESC, event_count DESC;


-- UTM Campaign Performance
CREATE OR REPLACE VIEW v_mixpanel_campaign_performance AS
SELECT 
    utm_source,
    utm_medium,
    utm_campaign,
    DATE(time_datetime) AS event_date,
    COUNT(*) AS event_count,
    COUNT(DISTINCT distinct_id) AS unique_users
FROM mixpanel_events
WHERE utm_source IS NOT NULL
GROUP BY utm_source, utm_medium, utm_campaign, DATE(time_datetime)
ORDER BY event_date DESC, unique_users DESC;


-- Revenue Summary
CREATE OR REPLACE VIEW v_mixpanel_revenue AS
SELECT 
    DATE(time_datetime) AS event_date,
    event,
    `$currency` AS currency,
    COUNT(*) AS transaction_count,
    COUNT(DISTINCT distinct_id) AS unique_customers,
    SUM(`$revenue`) AS total_revenue,
    AVG(`$revenue`) AS avg_revenue,
    MIN(`$revenue`) AS min_revenue,
    MAX(`$revenue`) AS max_revenue
FROM mixpanel_events
WHERE `$revenue` IS NOT NULL
GROUP BY DATE(time_datetime), event, `$currency`
ORDER BY event_date DESC, total_revenue DESC;


